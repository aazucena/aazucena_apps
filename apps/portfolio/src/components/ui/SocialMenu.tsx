// Hardcoded fallback (used if CMS unavailable)
const FALLBACK_SOCIAL_LINKS: SocialLink[] = [
  {
    platform: "GitHub",
    url: "https://github.com/yourusername",
    openInNewTab: true,
  },
  {
    platform: "LinkedIn",
    url: "https://linkedin.com/in/yourusername",
    openInNewTab: true,
  },
];

export function SocialMenu({
  onClose,
  socialLinks: propSocialLinks,
  email,
  emailDescription,
}: SocialMenuProps): JSX.Element {
  // Use provided socialLinks, fallback to hardcoded if unavailable
  let socialLinks =
    propSocialLinks && propSocialLinks.length > 0
      ? [...propSocialLinks] // Clone array to avoid mutating original
      : FALLBACK_SOCIAL_LINKS;

  // AUTOMATICALLY ADD EMAIL: Inject email as a social link if provided
  // Creates a pseudo-platform "Email" that's not in Strapi but useful for users
  if (email && !socialLinks.some((link) => link.url.includes("mailto:"))) {
    // Create email link object (cast to SocialLink for type compatibility)
    const emailLink = {
      platform: "Email" as SocialLink["platform"], // Type assertion (Email not in enum)
      url: `mailto:${email}`,
      text: "Email",
      description: emailDescription, // Custom description from CMS (falls back in render)
      openInNewTab: false, // Email clients typically don't open in new tab
    };

    // Add email as first item (most important contact method)
    socialLinks = [emailLink as SocialLink, ...socialLinks];
  }

  return (
    <div className="max-h-[85vh] overflow-y-auto p-4">
      <div className="mb-4 flex items-center justify-between">
        <h3 className="text-lg font-bold text-white">Connect</h3>
        <button
          onClick={onClose}
          className="text-white/60 transition-colors hover:text-white"
          aria-label="Close social menu"
        >
          <svg
            className="h-5 w-5"
            fill="none"
            stroke="currentColor"
            viewBox="0 0 24 24"
          >
            <path
              strokeLinecap="round"
              strokeLinejoin="round"
              strokeWidth={2}
              d="M6 18L18 6M6 6l12 12"
            />
          </svg>
        </button>
      </div>

      <div className="space-y-3">
        {socialLinks.length > 0 ? (
          socialLinks.map((link, index) => {
            const platformConfig = platformIcons[link.platform];
            if (!platformConfig) return null; // Skip unknown platforms

            return (
              <a
                key={`${link.platform}-${index}`}
                href={link.url}
                target={link.openInNewTab !== false ? "_blank" : undefined}
                rel={
                  link.openInNewTab !== false
                    ? "noopener noreferrer"
                    : undefined
                }
                className="group flex items-center gap-3 rounded-xl border border-white/10 bg-white/5 p-3 transition-all duration-300 hover:border-white/20 hover:bg-white/10"
              >
                <div className="flex h-10 w-10 items-center justify-center rounded-lg bg-white/10 transition-colors group-hover:bg-white/20">
                  {platformConfig.icon}
                </div>
                <div className="flex-1">
                  <div className="font-semibold text-white transition-colors group-hover:text-cyan-400">
                    {link.text || link.platform}
                  </div>
                  <div className="text-xs text-white/60">
                    {link.description || platformConfig.description}
                  </div>
                </div>
                <svg
                  className="h-5 w-5 text-white/40 transition-colors group-hover:text-white/80"
                  fill="none"
                  stroke="currentColor"
                  viewBox="0 0 24 24"
                >
                  <path
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    strokeWidth={2}
                    d="M9 5l7 7-7 7"
                  />
                </svg>
              </a>
            );
          })
        ) : (
          <div className="py-4 text-center text-white/60">
            No social links available
          </div>
        )}
      </div>
    </div>
  );
}
